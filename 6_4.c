#include <stdio.h>

int main(void) {
    double income;
    double tax = 0.0;
    double step1 = 0.0, step2 = 0.0, step3 = 0.0;

    printf("Введите величину дохода: ");
    if (scanf("%lif", &income) != 1 || income < 0) {
        printf("Ошибка: некорректный ввод дохода.\n");
        return 1;
    }

    // Ступенчатый расчет налога
    if (income <= 300.0) {
        step1 = income * 0.15;
        tax = step1;
    } else if (income <= 450.0) {
        step1 = 300.0 * 0.15;
        step2 = (income - 300.0) * 0.20;
        tax = step1 + step2;
    } else {
        step1 = 300.0 * 0.15;
        step2 = (450.0 - 300.0) * 0.20;
        step3 = (income - 450.0) * 0.25;
        tax = step1 + step2 + step3;
    }

    printf("\n--- Разбивка по тарифным ступеням ---\n");
    printf("Исходная величина дохода: %.2f\n", income);
    printf("1-я ступень (15%% до 300): %.2f\n", step1);
    printf("2-я ступень (20%% от 300 до 450): %.2f\n", step2);
    printf("3-я ступень (25%% свыше 450): %.2f\n", step3);
    printf("Итоговая сумма налога: %.2f\n", tax);

    return 0;
}

/*
================================================================================
ОТВЕТ НА ТЕОРЕТИЧЕСКИЙ ВОПРОС:
Почему предпочтительно использовать тип double, а не float для финансовых расчетов?
Тип `float` имеет точность всего около 6–7 значащих десятичных цифр, в то время как 
`double` предоставляет 15–17 значащих цифр. При постоянном сложении, вычитании 
или умножении денежных сумм во `float` очень быстро накапливаются ошибки округления 
(из-за специфики представления чисел с плавающей точкой в формате IEEE 754), 
что недопустимо для бухгалтерских и финансовых задач.
================================================================================
*/
