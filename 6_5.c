#include <stdio.h>

int main(void) {
    int choice;
    double temp_in, temp_out;

    while (1) {
        printf("\n======= МЕНЮ КОНВЕРТЕРА ТЕМПЕРАТУР =======\n");
        printf("1. Конвертация: Цельсий -> Фаренгейт (C -> F)\n");
        printf("2. Конвертация: Фаренгейт -> Цельсий (F -> C)\n");
        printf("3. Конвертация: Цельсий -> Кельвин (C -> K)\n");
        printf("4. Конвертация: Кельвин -> Цельсий (K -> C)\n");
        printf("5. Выход\n");
        printf("Выберите пункт меню (1-5): ");

        if (scanf("%d", &choice) != 1) {
            printf("Ошибка: введено не число! Попробуйте снова.\n");
            while (getchar() != '\n'); // Очистка буфера от некорректного ввода
            continue;
        }

        if (choice == 5) {
            printf("Выход из программы. До свидания!\n");
            break; // Выход из бесконечного цикла while
        }

        switch (choice) {
            case 1:
                printf("Введите температуру в Цельсиях: ");
                scanf("%lif", &temp_in);
                temp_out = (temp_in * 9.0 / 5.0) + 32.0;
                printf("%.2f C = %.2f F\n", temp_in, temp_out);
                break;

            case 2:
                printf("Введите температуру в Фаренгейтах: ");
                scanf("%lif", &temp_in);
                temp_out = (temp_in - 32.0) * 5.0 / 9.0;
                printf("%.2f F = %.2f C\n", temp_in, temp_out);
                break;

            case 3:
                printf("Введите температуру в Цельсиях: ");
                scanf("%lif", &temp_in);
                temp_out = temp_in + 273.15;
                printf("%.2f C = %.2f K\n", temp_in, temp_out);
                break;

            case 4:
                printf("Введите температуру в Кельвинах: ");
                scanf("%lif", &temp_in);
                if (temp_in < 0) {
                    printf("Ошибка: температура не может быть ниже Абсолютного нуля (0 К)!\n");
                } else {
                    temp_out = temp_in - 273.15;
                    printf("%.2f K = %.2f C\n", temp_in, temp_out);
                }
                break;

            default:
                printf("Некорректный выбор пункта меню! Пожалуйста, выберите от 1 до 5.\n");
                continue; // Пропускает оставшуюся часть цикла и выводит меню заново
        }
    }

    return 0;
}

/*
================================================================================
ОТВЕТ НА ТЕОРЕТИЧЕСКИЙ ВОПРОС:
Что произойдет, если забыть оператор break в одной из меток case?
Если в конце блока `case` отсутствует `break`, то выполнение программы не выйдет 
из оператора `switch`, а продолжится ("провалится", эффект fall-through) в код 
следующего по порядку `case` или `default`, независимо от того, истинно ли его 
условие. Это приведет к логической ошибке, когда вместе с выбранным действием 
выполнятся инструкции из нижестоящей ветки.
================================================================================
*/
